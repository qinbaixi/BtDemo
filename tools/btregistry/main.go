// Command btregistry scans the Go files owl-bt exported into the current
// directory and writes registry.go, which maps each tree name to its data.
//
// Run it with `go generate ./internal/ai/trees`.
package main

import (
	"bytes"
	"fmt"
	"go/ast"
	"go/format"
	"go/parser"
	"go/token"
	"log"
	"os"
	"path/filepath"
	"regexp"
	"sort"
	"strings"
)

var header = regexp.MustCompile(`Code generated by owl-bt from (\S+)\. DO NOT EDIT\.`)

type tree struct {
	name, root, nodes string
}

func main() {
	files, err := filepath.Glob("*.go")
	if err != nil {
		log.Fatal(err)
	}
	var pkg string
	var trees []tree
	fset := token.NewFileSet()
	for _, path := range files {
		src, err := os.ReadFile(path)
		if err != nil {
			log.Fatal(err)
		}
		m := header.FindSubmatch(src)
		if m == nil {
			continue
		}
		f, err := parser.ParseFile(fset, path, src, 0)
		if err != nil {
			log.Fatal(err)
		}
		pkg = f.Name.Name
		t := tree{name: strings.TrimSuffix(filepath.Base(string(m[1])), ".json")}
		for _, decl := range f.Decls {
			gd, ok := decl.(*ast.GenDecl)
			if !ok {
				continue
			}
			for _, spec := range gd.Specs {
				vs, ok := spec.(*ast.ValueSpec)
				if !ok {
					continue
				}
				for _, id := range vs.Names {
					switch {
					case gd.Tok == token.CONST && strings.HasSuffix(id.Name, "RootID"):
						t.root = id.Name
					case gd.Tok == token.VAR && strings.HasSuffix(id.Name, "Nodes"):
						t.nodes = id.Name
					}
				}
			}
		}
		if t.root == "" || t.nodes == "" {
			log.Fatalf("%s: RootID or Nodes not found", path)
		}
		trees = append(trees, t)
	}
	if pkg == "" {
		log.Fatal("no owl-bt exports found")
	}
	sort.Slice(trees, func(i, j int) bool { return trees[i].name < trees[j].name })

	var b bytes.Buffer
	fmt.Fprintf(&b, "// Code generated by tools/btregistry. DO NOT EDIT.\n\npackage %s\n\n", pkg)
	b.WriteString("// All maps each exported tree, by file name without .json, to its data.\n")
	b.WriteString("var All = map[string]Exported{\n")
	for _, t := range trees {
		fmt.Fprintf(&b, "\t%q: {RootID: %s, Nodes: %s},\n", t.name, t.root, t.nodes)
	}
	b.WriteString("}\n")
	out, err := format.Source(b.Bytes())
	if err != nil {
		log.Fatal(err)
	}
	if err := os.WriteFile("registry.go", out, 0o644); err != nil {
		log.Fatal(err)
	}
	fmt.Printf("registry.go: %d trees\n", len(trees))
}
