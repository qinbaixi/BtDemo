// Command btregistry 扫描 owl-bt 导出到当前目录中的 Go 文件，并写出 registry.go，将每棵树的名称映射到其数据。
//
// 使用 `go generate ./internal/ai/trees` 运行它。
package main

import (
	"bytes"
	"fmt"
	"go/ast"
	"go/format"
	"go/parser"
	"go/token"
	"log"
	"os"
	"path/filepath"
	"regexp"
	"sort"
	"strconv"
	"strings"
)

var header = regexp.MustCompile(`Code generated by owl-bt from (\S+)\. DO NOT EDIT\.`)

type tree struct {
	name, root, nodes string
	labels            map[int]string // 节点 id -> 编辑器里给节点起的名字（导出时写在注释里）
}

// labelComment 匹配导出器写在每个节点前面的注释，例如 "// Selector - 近战怪物"。
var labelComment = regexp.MustCompile(`^//\s*\S+ - (.+)$`)

func main() {
	files, err := filepath.Glob("*.go")
	if err != nil {
		log.Fatal(err)
	}
	var pkg string
	var trees []tree
	fset := token.NewFileSet()
	for _, path := range files {
		src, err := os.ReadFile(path)
		if err != nil {
			log.Fatal(err)
		}
		match := header.FindSubmatch(src)
		if match == nil {
			continue
		}
		file, err := parser.ParseFile(fset, path, src, parser.ParseComments)
		if err != nil {
			log.Fatal(err)
		}
		pkg = file.Name.Name
		tr := tree{name: strings.TrimSuffix(filepath.Base(string(match[1])), ".json")}
		for _, decl := range file.Decls {
			genDecl, ok := decl.(*ast.GenDecl)
			if !ok {
				continue
			}
			for _, spec := range genDecl.Specs {
				valueSpec, ok := spec.(*ast.ValueSpec)
				if !ok {
					continue
				}
				for _, id := range valueSpec.Names {
					switch {
					case genDecl.Tok == token.CONST && strings.HasSuffix(id.Name, "RootID"):
						tr.root = id.Name
					case genDecl.Tok == token.VAR && strings.HasSuffix(id.Name, "Nodes"):
						tr.nodes = id.Name
						tr.labels = nodeLabels(fset, file, valueSpec)
					}
				}
			}
		}
		if tr.root == "" || tr.nodes == "" {
			log.Fatalf("%s: RootID or Nodes not found", path)
		}
		trees = append(trees, tr)
	}
	if pkg == "" {
		log.Fatal("no owl-bt exports found")
	}
	sort.Slice(trees, func(i, j int) bool { return trees[i].name < trees[j].name })

	var buf bytes.Buffer
	fmt.Fprintf(&buf, "// Code generated by tools/btregistry. DO NOT EDIT.\n\npackage %s\n\n", pkg)
	buf.WriteString("// All 把每棵导出的树按文件名（不含 .json）映射到它的数据。\n")
	buf.WriteString("var All = map[string]Exported{\n")
	for _, tr := range trees {
		fmt.Fprintf(
			&buf,
			"\t%q: {RootID: %s, Nodes: %s, Labels: map[int]string{",
			tr.name,
			tr.root,
			tr.nodes,
		)
		ids := make([]int, 0, len(tr.labels))
		for id := range tr.labels {
			ids = append(ids, id)
		}
		sort.Ints(ids)
		for i, id := range ids {
			if i > 0 {
				buf.WriteString(", ")
			}
			fmt.Fprintf(&buf, "%d: %q", id, tr.labels[id])
		}
		buf.WriteString("}},\n")
	}
	buf.WriteString("}\n")
	out, err := format.Source(buf.Bytes())
	if err != nil {
		log.Fatal(err)
	}
	if err := os.WriteFile("registry.go", out, 0o644); err != nil {
		log.Fatal(err)
	}
	fmt.Printf("registry.go: %d trees\n", len(trees))
}

// nodeLabels 从 Nodes 字面量里每个条目前一行的注释取出节点名字。
func nodeLabels(fset *token.FileSet, file *ast.File, valueSpec *ast.ValueSpec) map[int]string {
	labels := map[int]string{}
	if len(valueSpec.Values) != 1 {
		return labels
	}
	lit, ok := valueSpec.Values[0].(*ast.CompositeLit)
	if !ok {
		return labels
	}
	// 按行号索引注释，条目上一行的注释就是它的说明
	byLine := map[int]string{}
	for _, group := range file.Comments {
		for _, comment := range group.List {
			byLine[fset.Position(comment.Slash).Line] = comment.Text
		}
	}
	for _, el := range lit.Elts {
		kv, ok := el.(*ast.KeyValueExpr)
		if !ok {
			continue
		}
		key, ok := kv.Key.(*ast.BasicLit)
		if !ok || key.Kind != token.INT {
			continue
		}
		id, err := strconv.Atoi(key.Value)
		if err != nil {
			continue
		}
		line := byLine[fset.Position(kv.Pos()).Line-1]
		if match := labelComment.FindStringSubmatch(line); match != nil {
			labels[id] = strings.TrimSpace(match[1])
		}
	}
	return labels
}
